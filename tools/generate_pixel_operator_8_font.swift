#!/usr/bin/env swift

import CoreGraphics
import CoreText
import CryptoKit
import Foundation

func pixelCoordinate(_ value: CGFloat) -> Int {
  let rounded = value.rounded()
  precondition(abs(value - rounded) < 0.00001, "Off-grid coordinate or metric: \(value)")
  return Int(rounded)
}

func validateGrid(_ path: CGPath) {
  var start = CGPoint.zero
  var previous = CGPoint.zero

  func checkEdge(to point: CGPoint) {
    precondition(
      pixelCoordinate(point.x) == pixelCoordinate(previous.x)
        || pixelCoordinate(point.y) == pixelCoordinate(previous.y),
      "Non-axis-aligned glyph edge")
    previous = point
  }

  path.applyWithBlock { element in
    switch element.pointee.type {
    case .moveToPoint:
      start = element.pointee.points[0]
      _ = pixelCoordinate(start.x)
      _ = pixelCoordinate(start.y)
      previous = start
    case .addLineToPoint:
      let point = element.pointee.points[0]
      _ = pixelCoordinate(point.x)
      _ = pixelCoordinate(point.y)
      checkEdge(to: point)
    case .closeSubpath:
      checkEdge(to: start)
    default:
      preconditionFailure("Curved glyph outline")
    }
  }
}

let sourceURL = URL(fileURLWithPath: #filePath).deletingLastPathComponent()
  .appendingPathComponent("fonts/PixelOperator8.ttf")
let source = try Data(contentsOf: sourceURL)
let sha256 = SHA256.hash(data: source).map { String(format: "%02x", $0) }.joined()
precondition(sha256 == "5cccb9ef6cf18977b6e5721d49a1a6e78dd6a6f1c4f69537470f7dc1dc829ffc")
let graphicsFont = CGFont(CGDataProvider(data: source as CFData)!)!
let font = CTFontCreateWithGraphicsFont(graphicsFont, 8, nil, nil)
let ascent = pixelCoordinate(CTFontGetAscent(font))
let descent = pixelCoordinate(CTFontGetDescent(font))
let lineHeight = ascent + descent + Int(CTFontGetLeading(font).rounded(.up))

let advanceReduction = 1  // Tighten spacing by one native pixel, including spaces.
let scalars: ClosedRange<UInt16> = 32...126
var bitmap: [UInt8] = []
var glyphs: [String] = []
var maxPixels = 0

for scalar in scalars {
  var character = scalar
  var glyph: CGGlyph = 0
  precondition(CTFontGetGlyphsForCharacters(font, &character, &glyph, 1), "Missing scalar \(scalar)")
  let sourceAdvance = pixelCoordinate(CTFontGetAdvancesForGlyphs(font, .horizontal, &glyph, nil, 1))
  let advance = sourceAdvance - advanceReduction
  precondition(advance > 0, "Adjusted advance must be positive for scalar \(scalar)")
  let offset = bitmap.count
  var left = 0
  var top = 0
  var width = 0
  var height = 0

  if let path = CTFontCreatePathForGlyph(font, glyph, nil), !path.isEmpty {
    validateGrid(path)
    let bounds = path.boundingBoxOfPath
    left = pixelCoordinate(bounds.minX)
    top = pixelCoordinate(bounds.maxY)
    width = pixelCoordinate(bounds.maxX) - left
    height = top - pixelCoordinate(bounds.minY)

    // Every edge lies on the native grid, so its nonzero winding fill is
    // constant throughout each pixel interior. Sample once at the centre.
    var byte: UInt8 = 0
    var mask: UInt8 = 0x80
    for row in 0..<height {
      for column in 0..<width {
        if path.contains(CGPoint(x: Double(left + column) + 0.5, y: Double(top - row) - 0.5)) {
          byte |= mask
        }
        mask >>= 1
        if mask == 0 {
          bitmap.append(byte)
          byte = 0
          mask = 0x80
        }
      }
    }
    if mask != 0x80 {
      bitmap.append(byte)
    }
  }

  maxPixels = max(maxPixels, width * height)
  glyphs.append(
    "    Glyph(bitmapOffset: \(offset), width: \(width), height: \(height), left: \(left), top: \(-top), advance: \(advance)),"
  )
}

let bitmapRows = stride(from: 0, to: bitmap.count, by: 16).map { start in
  "    " + bitmap[start..<min(start + 16, bitmap.count)].map { String(format: "0x%02x", $0) }.joined(separator: ", ")
    + ","
}
let output = """
  //
  //  PixelOperator8Font.swift
  //  sk-radio-clock
  //
  //  Generated by tools/generate_pixel_operator_8_font.swift.
  //  Do not edit by hand.
  //  Pixel Operator 8 2018.10.04-1 by Jayvee Enaguas, CC0 1.0.
  //  Native 8 px outlines, U+0020...U+007E.
  //

  enum PixelOperator8Font: Font {
    static let pixelFormat: PixelFormat = .a1
    static let ascent = \(ascent)
    static let descent = \(descent)
    static let lineHeight = \(lineHeight)
    static let maxGlyphPixelCount = \(maxPixels)

    private static let firstScalarValue: UInt32 = \(scalars.lowerBound)
    private static let lastScalarValue: UInt32 = \(scalars.upperBound)

    private static let bitmap: InlineArray<\(bitmap.count), UInt8> = [
  \(bitmapRows.joined(separator: "\n"))
    ]

    private static let glyphs: InlineArray<\(glyphs.count), Glyph<PixelOperator8Font>> = [
  \(glyphs.joined(separator: "\n"))
    ]

    static func glyph(for scalar: Unicode.Scalar) -> Glyph<Self>? {
      guard scalar.value >= firstScalarValue, scalar.value <= lastScalarValue else { return nil }
      return glyphs[Int(scalar.value - firstScalarValue)]
    }

    static func withCoverage<Result>(
      for glyph: Glyph<Self>,
      _ body: (Span<UInt8>) -> Result
    ) -> Result {
      let count = glyph.width * glyph.height
      var decoded: InlineArray<\(maxPixels), UInt8> = .init(repeating: 0)
      var byteIndex = glyph.bitmapOffset
      var mask: UInt8 = 0x80
      for index in 0..<count {
        decoded[index] = bitmap[byteIndex] & mask == 0 ? 0 : 255
        mask >>= 1
        if mask == 0 {
          byteIndex += 1
          mask = 0x80
        }
      }
      return body(decoded.span.extracting(0..<count))
    }
  }

  """

let outputPath = CommandLine.arguments.dropFirst().first ?? "src/render/fonts/PixelOperator8Font.swift"
try output.write(toFile: outputPath, atomically: true, encoding: .utf8)
